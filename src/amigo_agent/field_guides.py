"""인수인계서 항목별 작성 기준(노션 '인수인계서 형식' 표의 정보 추출 기준 · 보완 질문 예시 · 구체적 질문 예시 · 작성 예시 · 작성 가이드 · 질문 조건).

핵심 질문은 template.FieldSpec.hint 에 있고, 여기에는 나머지 설명을 장(slot)·필드별로 옮겨 둔다.
AI 는 이 기준을 세 곳에서 쓴다(prompts.py). 질문은 양식의 빈 칸(또는 빈 세부사항)에만 한다(양식에 없는 질문은 만들지 않는다).
- 자료 분석: 정보 추출 기준(세부사항)과 작성 가이드로 '자료로 이 칸을 채울 수 있는지'를 판단하고, 확인할 수 없는 세부사항만 질문으로 남긴다.
  값은 작성 예시의 형식(구조·번호·라벨)을 따른다.
- 질문 만들기: 질문 문장은 구체적 질문 예시를 따른다(보완 질문 예시는 참고용).
  칸이 통째로 비었으면 코드가 묻는다(first_ask_example: 구체적 질문 예시 중 자료 없이도 물을 수 있는 문장(empty_ask), 없으면 보완 질문 예시).
  일부 세부사항만 빠졌으면 그 세부사항만 구체적 질문 예시를 본떠 묻는다(1질문 1암묵지).
- 답변 해석: 답을 칸에 정리할 때 작성 예시의 형식을 따른다.
예/아니요로 먼저 묻는 항목(FieldSpec.gate)은 gate_question 으로 묻고, '예'면 이어서 묻는다.

세부사항 표시
- '(필수)': 노션 표에서 굵은 글씨인 세부사항. 칸 값에 반드시 들어가야 하고, 자료에서 찾지 못하면 반드시 묻는다(필수 질문).
- '(보조)': 보조 세부사항. 빠졌으면 보조질문(건너뛰어도 되는 질문)으로 묻는다.
- 표시 없음: 질문 조건이 묻으라고 할 때만 묻는다.
required 는 항목 이름 자체가 굵은 글씨(★수행 절차★ 등)인 항목이다(비워 둘 수 없음).
ask_elements 가 있으면 그 칸은 그 세부사항만 묻는다(예: 수행 절차는 순서 확인 · 검토 기준 · 승인 절차만).

장 안에 표로 들어가는 장(협업관계·추진 경과·연락망)은 필드 대신 장 전체에 기준이 있으므로 키 "*" 에 둔다.
노션 표가 바뀌면 이 파일만 고친다.
"""

from __future__ import annotations

