def guide_for(slot_key: str, field_key: str = "*") -> FieldGuide | None:
    return (GUIDES.get(slot_key) or {}).get(field_key)


def first_ask_example(slot_key: str, field_key: str) -> str:
    """코드가 칸 전체를 물을 때 쓰는 질문 예시(그 필드의 첫 질문 예시). 장 전체 기준의 질문 예시는 한 칸만 묻는 질문에 맞지 않아 쓰지 않는다."""
    guide = guide_for(slot_key, field_key)
    return guide.ask_examples[0] if guide and guide.ask_examples else ""


def gate_question(slot_key: str, field_key: str) -> str:
    """예/아니요로 먼저 묻는 질문(없으면 빈 문자열)."""
    guide = guide_for(slot_key, field_key)
    return guide.gate_question if guide else ""


