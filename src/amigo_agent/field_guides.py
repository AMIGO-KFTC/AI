def guide_for(slot_key: str, field_key: str = "*") -> FieldGuide | None:
    return (GUIDES.get(slot_key) or {}).get(field_key)


def first_ask_example(slot_key: str, field_key: str) -> str:
    """코드가 칸 전체가 비었을 때 묻는 문장. 질문은 구체적 질문 예시를 따르므로 그 칸의 empty_ask(첫 필수 세부사항을 묻는 구체적 질문 예시)를 먼저 쓰고,
    없으면 보완 질문 예시의 첫 문장을 쓴다. 장 전체 기준의 질문 예시는 한 칸만 묻는 질문에 맞지 않아 쓰지 않는다."""
    guide = guide_for(slot_key, field_key)
    if guide is None:
        return ""
    return guide.empty_ask or (guide.ask_examples[0] if guide.ask_examples else "")


def gate_question(slot_key: str, field_key: str) -> str:
    """예/아니요로 먼저 묻는 질문(없으면 빈 문자열)."""
    guide = guide_for(slot_key, field_key)
    return guide.gate_question if guide else ""


def match_element(slot_key: str, field_key: str, element: str) -> str:
    """모델이 쓴 세부사항 이름과 가장 많이 겹치는 노션 세부사항(표시 포함). 글자쌍이 2개 이상 겹치지 않으면 빈 문자열."""
    guide = guide_for(slot_key, field_key)
    if guide is None or not element.strip():
        return ""
    target = _plain_bigrams(element)
    best = max(guide.elements, key=lambda e: len(_plain_bigrams(e) & target), default="")
    return best if len(_plain_bigrams(best) & target) >= 2 else ""


def _plain_bigrams(text: str) -> set[str]:
    """'(필수)'·'(보조)' 표시를 뺀 글자쌍(표시 글자가 겹친다고 같은 세부사항으로 보지 않게)."""
    return bigrams(text.replace(REQUIRED, "").replace(AUX, ""))


def is_required_element(slot_key: str, field_key: str, element: str) -> bool:
    """노션 표에서 굵은 글씨인 세부사항('(필수)')인지."""
    return match_element(slot_key, field_key, element).startswith(REQUIRED)


def element_askable(slot_key: str, field_key: str, element: str) -> bool:
    """그 칸에서 이 세부사항을 질문으로 만들 수 있는지. ask_elements 가 정해진 칸(수행 절차)은 그 세부사항만 묻는다."""
    guide = guide_for(slot_key, field_key)
    if guide is None or not guide.ask_elements or not element.strip():
        return True
    return match_element(slot_key, field_key, element) in guide.ask_elements


def cap_element_questions(slot_key: str, gaps: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """ask_elements 가 정해진 칸(수행 절차)은 항목마다 묻는 세부사항 하나에 질문 하나만 남긴다(노션 표: 절차의 정확성만 확인).
    묻지 않는 세부사항(단계별 세부 설명·자료·양식 등)을 묻는 질문은 버린다."""
    out: list[dict[str, Any]] = []
    seen: set[tuple[str, str, str]] = set()
    for gap in gaps:
        field_key = str(gap.get("field") or "")
        guide = guide_for(slot_key, field_key)
        element = str(gap.get("element") or "")
        if guide is None or not guide.ask_elements or not element.strip():
            out.append(gap)
            continue
        target = match_element(slot_key, field_key, element)
        key = (str(gap.get("item_id") or ""), field_key, target)
        if target not in guide.ask_elements or key in seen:
            continue
        seen.add(key)
        out.append(gap)
    return out


