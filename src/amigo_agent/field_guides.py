REQUIRED = "(필수)"
AUX = "(보조)"


@dataclass(frozen=True)
class FieldGuide:
    ask_examples: tuple[str, ...] = ()  # 보완 질문 예시(참고용. 구체적 질문 예시가 없을 때 코드가 칸 전체를 묻는 문장으로 쓴다)
    elements: tuple[str, ...] = ()  # 정보 추출 기준: 이 칸에 들어가야 하는 세부사항(암묵지 판단 단위). '(필수)' = 노션 굵은 글씨, '(보조)' = 보조
    detail_examples: tuple[str, ...] = ()  # 구체적 질문 예시(질문 문장은 이 예시를 따른다)
    example: str = ""  # 작성 예시(칸 값의 형식)
    guide: str = ""  # 작성 가이드
    ask_when: str = ""  # 질문 조건
    gate_question: str = ""  # 예/아니요로 먼저 묻는 질문(자료에서 관련 내용을 찾지 못했을 때)
    empty_ask: str = ""  # 칸이 통째로 비었을 때 코드가 묻는 구체적 질문 예시(첫 필수 세부사항, 없으면 첫 세부사항을 묻는 문장. 자료를 전제하지 않는 것만)
    ask_elements: tuple[str, ...] = ()  # 이 칸에서 질문으로 만들 수 있는 세부사항(비어 있으면 모든 세부사항)
    required: bool = False  # 항목 이름이 굵은 글씨인 필수 항목

    @property
    def required_elements(self) -> tuple[str, ...]:
        return tuple(e for e in self.elements if e.startswith(REQUIRED))

    def lines(self) -> list[str]:
        out = []
        if self.required:
            out.append("필수 항목(노션 양식 굵은 글씨): 비워 둘 수 없습니다.")
        if self.elements:
            out.append("세부사항(정보 추출 기준): " + " / ".join(self.elements))
        if self.ask_elements:
            out.append("묻는 세부사항(이 세부사항만 질문으로 만듦): " + " / ".join(self.ask_elements))
        if self.guide:
            out.append(f"작성 가이드: {self.guide}")
        if self.example:
            out.append(f"작성 예시: {self.example}")
        if self.detail_examples:
            out.append("구체적 질문 예시(질문 문장은 이 예시를 따름): " + " / ".join(self.detail_examples))
        if self.ask_examples:
            out.append("보완 질문 예시(참고용): " + " / ".join(self.ask_examples))
        if self.ask_when:
            out.append(f"질문 조건: {self.ask_when}")
        return out


