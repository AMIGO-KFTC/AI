    example: str = ""  # 작성 예시
    guide: str = ""  # 작성 가이드
    ask_when: str = ""  # 질문 조건

    def lines(self) -> list[str]:
        out = []
        if self.guide:
            out.append(f"작성 가이드: {self.guide}")
        if self.example:
            out.append(f"작성 예시: {self.example}")
        if self.ask_examples:
            out.append("질문 예시: " + " / ".join(self.ask_examples))
        if self.ask_when:
            out.append(f"질문 조건: {self.ask_when}")
        return out


