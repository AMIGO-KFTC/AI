"""인계자 답변을 코드로 다루는 작은 규칙.

답이 질문과 상관있는지, 정리한 값이 인계자의 말에서 나왔는지, 건너뛰어도 되는지는 모델(Claude Opus)의 판단을 따른다
(예전에 두었던 글자 겹침·표현 목록 검사는 정상 답을 막아서 뺐다). 여기에는 두 가지만 남긴다.
- is_none_answer: 묻는 칸에 해당하는 것이 없다는 답('그런 것은 없어')이면 그 칸을 '해당 없음'으로 채운다(노션 양식: '없다면 해당 없음으로 처리').
- bigrams: 글자쌍(문서의 근거 번호를 근거 문장과 가장 많이 겹치는 칸 뒤에 달 때 쓴다, render.py).
"""

from __future__ import annotations

import re


# 어느 문장에나 붙는 끝맺음 글자쌍(입니다·습니다·해요 …)은 같은 말을 했다는 증거가 못 되므로 비교에서 뺀다.
ENDING_BIGRAMS = {"니다", "입니", "습니", "합니", "됩니", "있습", "없습", "했습", "었습", "였습", "아요", "어요", "여요", "해요", "세요", "에요", "예요", "이에", "이예", "이다", "했다", "한다", "된다", "있다", "없다"}


def bigrams(text: str) -> set[str]:
    chars = re.sub(r"[^가-힣A-Za-z0-9]", "", (text or "").lower())
    return {chars[i : i + 2] for i in range(len(chars) - 1)} - ENDING_BIGRAMS


# 묻는 칸에 해당하는 것이 '없다'는 답(모른다는 답과 다르다). 이 답은 칸을 '해당 없음'으로 채운다(노션 양식: '없다면 해당 없음으로 처리').
UNKNOWN_RE = re.compile(r"모르|몰라|모름|기억|확인(이)?\s*어렵|알 수 없|생각(이)?\s*안\s*나|나중에")
NONE_RE = re.compile(
    r"해당\s*(사항)?\s*(이|은|는)?\s*없|(그런|그러한|이런|별다른|따로|딱히|특별히|특별한|별로|아무)\s*\S{0,6}\s*없"
    r"|^\s*(없|없음|없어|없어요|없습니다|없다|없네요|없는데요?|없었어요?|없었습니다)\s*[.!~]*\s*$"
    r"|(것|거|건|게|점|일|사항|내용|결정|문제)\s*(은|는|이|가|도)?\s*(전혀\s*)?없(어|어요|음|습니다|다|네요|었어요?|었습니다)?\s*[.!~]*\s*$"
)


def is_none_answer(text: str) -> bool:
    """묻는 칸에 해당하는 것이 없다는 답인지('그런 것은 없어', '딱히 없어요', '해당 없음'). 모른다는 말이 섞이면 아니다."""
    raw = " ".join((text or "").split())
    return bool(raw) and len(raw) <= 40 and not UNKNOWN_RE.search(raw) and bool(NONE_RE.search(raw))
